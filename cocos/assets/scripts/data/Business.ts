// 抽一步：保留原玩法的计算或流程。
ctx.pickNextStep = function (gameEntries?: any) {
    const possible: any = gameEntries.filter((x?: any) => x["需"] !== false);
    const gameTotal: any = possible.reduce((a?: any, x?: any) => a + (x["重"] || 1), 0);
    let r: any = Math.random() * gameTotal;
    for (const x of possible) {
        r -= (x["重"] || 1);
        if (r < 0)
            return x.step;
    }
    return possible[0].step;
};

